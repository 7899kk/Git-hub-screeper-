from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':412,'height':915})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' and 'Failed to load resource' not in m.text else None)
    page.goto('http://127.0.0.1:8082')
    page.get_by_role('button',name='Continue',exact=True).click()
    page.get_by_role('button',name='Continue',exact=True).click()
    page.get_by_role('button',name='Start comparing',exact=True).click()
    page.get_by_role('button',name='Settings',exact=True).click()
    page.get_by_label('Backend URL',exact=True).fill('http://127.0.0.1:8010')
    page.get_by_role('button',name='Save connection',exact=True).click()
    expect(page.get_by_text('Connection saved.',exact=False)).to_be_visible()
    page.get_by_role('button',name='Home',exact=True).click()
    expect(page.get_by_text('No observed products yet',exact=True).filter(visible=True)).to_be_visible(timeout=15000)
    page.screenshot(path='artifacts/home-live-empty.png',full_page=True)
    page.get_by_role('button',name='Stores',exact=True).click()
    expect(page.get_by_text('Setup required',exact=True).first).to_be_visible(timeout=15000)
    assert page.get_by_text('Setup required',exact=True).count()>=18
    page.get_by_role('button',name='Find',exact=True).click()
    page.get_by_label('Product link',exact=True).fill('https://new-retailer.example/product')
    page.get_by_role('button',name='Identify product',exact=True).click()
    expect(page.get_by_text('Price unavailable for this link',exact=True)).to_be_visible(timeout=15000)
    page.get_by_role('button',name='Saved',exact=True).click()
    expect(page.get_by_text('Nothing saved yet',exact=True)).to_be_visible(timeout=15000)
    page.get_by_role('button',name='Open alerts',exact=True).click()
    expect(page.get_by_text('No price targets yet',exact=True)).to_be_visible(timeout=15000)
    page.goto('http://127.0.0.1:8082/search')
    expect(page.get_by_text('No observed matches',exact=True)).to_be_visible(timeout=15000)
    page.goto('http://127.0.0.1:8082/disclosures')
    expect(page.get_by_text('Affiliate disclosure',exact=True)).to_be_visible()
    page.route('**/products',lambda route:route.abort())
    page.goto('http://127.0.0.1:8082/')
    expect(page.get_by_text('Live service is unreachable.',exact=False)).to_be_visible(timeout=15000)
    assert not errors,errors
    print('PASS: Chromium mobile navigation, empty catalogue, retailer directory, unsupported resolver, privacy and offline errors; no runtime errors.')
    browser.close()
